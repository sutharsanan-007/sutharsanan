function observeReveals(root = document) {
  if (!revealAnimationsEnabled) return;
  if (!("IntersectionObserver" in window)) {
    $$(".reveal", root).forEach((el) => el.classList.add("visible"));
    return;
  }
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          entry.target
            .querySelectorAll(".skill-track span")
            .forEach((bar) => (bar.style.width = bar.dataset.width));
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -25px 0px" },
  );
  $$(".reveal", root).forEach((el, i) => {
    el.style.transitionDelay = `${Math.min(i % 4, 3) * 65}ms`;
    observer.observe(el);
  });
}
function setupPreloader(onComplete) {
  const preloader = $("#preloader"),
    percent = $("#loadPercent"),
    bar = $("#loaderBar");
  let value = 0;
  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const revealContent = (event) => {
    if (event.target !== preloader || event.propertyName !== "opacity") return;
    preloader.removeEventListener("transitionend", revealContent);
    revealAnimationsEnabled = true;
    onComplete();
  };
  preloader.addEventListener("transitionend", revealContent);
  const step = () => {
    value = Math.min(
      100,
      value + (reduced ? 35 : Math.ceil(Math.random() * 13)),
    );
    percent.textContent = String(value).padStart(2, "0");
    bar.style.width = value + "%";
    if (value >= 100) {
      setTimeout(() => preloader.classList.add("loaded"), reduced ? 0 : 260);
    } else setTimeout(step, reduced ? 10 : 55);
  };
  step();
}
function setupNav() {
  const nav = $(".site-nav"),
    menu = $("#siteMenu"),
    links = $$(".nav-link");
  const update = () => nav.classList.toggle("scrolled", window.scrollY > 24);
  window.addEventListener("scroll", update, { passive: true });
  update();
  $$("#siteMenu a").forEach((link) =>
    link.addEventListener("click", () => {
      if (link.matches(".nav-link")) {
        links.forEach((item) => item.classList.remove("active"));
        link.classList.add("active");
      }
      if (window.bootstrap && menu.classList.contains("show"))
        bootstrap.Collapse.getOrCreateInstance(menu).hide();
    }),
  );
  if ("IntersectionObserver" in window) {
    const sections = $$("main section[id]");
    const spy = new IntersectionObserver(
      (entries) =>
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            links.forEach((l) =>
              l.classList.toggle(
                "active",
                l.getAttribute("href") === "#" + entry.target.id,
              ),
            );
          }
        }),
      { rootMargin: "-35% 0px -55% 0px" },
    );
    sections.forEach((s) => spy.observe(s));
  }
}
