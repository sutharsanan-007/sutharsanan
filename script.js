function formatExperienceDuration(period, today = new Date()) {
  const range = period.match(
    /\b([A-Za-z]{3})\s+(\d{4})\s*-\s*(Present|[A-Za-z]{3}\s+\d{4})$/i,
  );
  if (!range) {
    throw new Error(`Unable to calculate experience duration from "${period}"`);
  }

  const months = [
    "jan",
    "feb",
    "mar",
    "apr",
    "may",
    "jun",
    "jul",
    "aug",
    "sep",
    "oct",
    "nov",
    "dec",
  ];
  const startMonth = months.indexOf(range[1].toLowerCase());
  if (startMonth === -1) {
    throw new Error(`Invalid start month in experience period "${period}"`);
  }

  const startIndex = Number(range[2]) * 12 + startMonth;
  const endIndex = /^present$/i.test(range[3])
    ? today.getFullYear() * 12 + today.getMonth()
    : (() => {
        const endRange = range[3].match(/^([A-Za-z]{3})\s+(\d{4})$/);
        const endMonth = endRange
          ? months.indexOf(endRange[1].toLowerCase())
          : -1;
        if (!endRange || endMonth === -1) {
          throw new Error(`Invalid end month in experience period "${period}"`);
        }
        return Number(endRange[2]) * 12 + endMonth;
      })();
  const totalMonths = endIndex - startIndex + 1;
  if (totalMonths < 1) {
    throw new Error(`Experience period ends before it starts: "${period}"`);
  }

  const years = Math.floor(totalMonths / 12);
  const remainingMonths = totalMonths % 12;
  return [
    years ? `${years} yr${years === 1 ? "" : "s"}` : "",
    remainingMonths
      ? `${remainingMonths} mo${remainingMonths === 1 ? "" : "s"}`
      : "",
  ]
    .filter(Boolean)
    .join(" ");
}

